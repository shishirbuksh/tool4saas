// Generates src/lib/astro/view-registry.ts from src/views/**/*.tsx so the
// hydration entry can lazy-load exactly one view chunk per page.
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = "src/views";

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.isFile() && entry.name.endsWith(".tsx") && !entry.name.endsWith(".test.tsx")) {
      out.push(full);
    }
  }
  return out;
}

const files = walk(ROOT).sort();
const entries = files.map((file) => {
  const rel = path.relative(ROOT, file).replace(/\\/g, "/").replace(/\.tsx$/, "");
  return `  ${JSON.stringify(rel)}: () => import("@/views/${rel}"),`;
});

const body = `// AUTO-GENERATED by scripts/generate-view-registry.mjs — do not edit.
// Maps the data-view key on #app to the React view module Astro should hydrate.
export const VIEW_REGISTRY: Record<string, () => Promise<unknown>> = {
${entries.join("\n")}
};
`;

writeFileSync("src/lib/astro/view-registry.ts", body);
console.log(`generate-view-registry: ${files.length} views`);
